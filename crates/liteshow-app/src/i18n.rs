//! Minimal zh/en strings for the UI.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Zh,
    En,
}

impl Lang {
    /// Follow the system locale: any `zh*` locale selects Chinese, other
    /// non-empty locales select English; fall back to Chinese.
    pub fn detect() -> Self {
        for var in ["LC_ALL", "LC_MESSAGES", "LANG"] {
            if let Ok(value) = std::env::var(var) {
                if value.is_empty() {
                    continue;
                }
                let lower = value.to_ascii_lowercase();
                return if lower.contains("zh") { Lang::Zh } else { Lang::En };
            }
        }
        Lang::Zh
    }
}

